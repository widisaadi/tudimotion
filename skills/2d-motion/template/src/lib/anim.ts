import { Easing, interpolate, spring } from "remotion";
import { FPS } from "./theme";

/** Springy 0→1 with a slight overshoot — the "pop" used for every entrance. */
export const pop = (f: number, delay = 0, damping = 11) =>
  spring({ frame: f - delay, fps: FPS, config: { damping, stiffness: 170, mass: 0.7 } });

/** Smooth 0→1 (ease-out) between two frames. */
export const ease = (f: number, a: number, b: number, from = 0, to = 1) =>
  interpolate(f, [a, b], [from, to], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
    easing: Easing.bezier(0.22, 1, 0.36, 1),
  });

export const bob = (f: number, speed = 0.13, amp = 6) => Math.sin(f * speed) * amp;

export const isBlinking = (f: number, period = 84, offset = 0) => (f + offset) % period < 4;

import beats from "../beats.json";

/**
 * Frame (inside scene `scene`, 1-based) where spoken phrase `phrase` (0-based) of that scene's voiceover starts,
 * plus `offset`. Generated by `npm run beats` from the real VO files, so animation lands on the words.
 * Use it for every beat that illustrates a sentence: `<Bubble start={beat(2, 3, -4)} … />`.
 */
export const beat = (scene: number, phrase: number, offset = 0): number => {
  const s = (beats as { scenes: { phrases: { start: number }[] }[] }).scenes[scene - 1];
  const p = s?.phrases[Math.min(phrase, (s?.phrases.length ?? 1) - 1)];
  return (p?.start ?? 0) + offset;
};
